print("lower() .........: ",s.lower())
print("swapcase() ......: ",s.swapcase())
print("capitalize() ....: ",s.capitalize())
print("title() .........: ",s.title())
print("count() .........: ",s.count("e"))
print("replace() .......: ",s.replace("e","a"))
print("split() .........: ",s.split(" "))
print('join() ..........: ',"@".join(s))
print("index() .........: ",s.index("e"))
print("rindex() ........: ",s.rindex("e"))
print("find() ..........: ",s.find("s"))
print("rfind() .........: ",s.rfind("s"))
print("strip() .........: ",s.strip())
print("rstrip() ........: ",s.rstrip())
print("center() ........: ",s.center(30,"*"))
print("isalpha() .......: ",s.isalpha())
print("isalnum() .......: ",s.isalnum())
print("isdigit() .......: ",s.isdigit())
print("islower() .......: ",s.islower())
print("isupper() .......: ",s.isupper())
print("len() ...........: ",len(s))